"""Synthesize sample clips from the fine-tuned TRIH voices (host_0, host_1).

Loads stock ChatterboxTTS, swaps in each host's fine-tuned t3_cfg.safetensors
(trih_state/s4/finetune_verbatim/<host>/), uses one of that host's own training
clips as the voice reference, and generates a few sample lines. Output WAVs ->
trih_state/s4/out/.
"""
import os, subprocess, sys, shutil

WORK = "/kaggle/working"; DRIVE = "gdrive_rw:trih_state"
HOSTS = ["host_0", "host_1"]
LINES = [
    "Hello, and welcome to PodcastSim. Just so we're clear: this is not a real recording. My voice is completely synthetic, generated by a machine learning model.",
    "I'm an AI clone, and honestly, I have no idea what I'm talking about. I have never read a history book in my life.",
    "This whole project takes a pile of podcast episodes and turns them into cloned host voices. Everything you are hearing right now was generated by a computer.",
]
GEN = {"cfg_weight": 0.3, "exaggeration": 0.9}   # exaggerated, theatrical delivery for the intro


def sh(c, check=True):
    print(f"$ {c}", flush=True); return subprocess.run(c, shell=True, check=check)


def find_secrets():
    for r, _d, fs in os.walk("/kaggle/input"):
        if "rclone.conf" in fs:
            return r
    sys.exit("secrets not attached")


def main():
    sec = find_secrets()
    if not shutil.which("rclone"):
        sh("curl -sL https://downloads.rclone.org/rclone-current-linux-amd64.zip -o /tmp/r.zip "
           "&& cd /tmp && unzip -q r.zip && cp rclone-*/rclone /usr/local/bin/ && chmod +x /usr/local/bin/rclone")
    os.makedirs(os.path.expanduser("~/.config/rclone"), exist_ok=True)
    shutil.copy(f"{sec}/rclone.conf", os.path.expanduser("~/.config/rclone/rclone.conf"))

    sh(f"{sys.executable} -m pip install -q chatterbox-tts", check=False)
    sh(f"{sys.executable} -m pip install -q --force-reinstall transformers==5.2.0", check=False)
    sh(f"{sys.executable} -m pip install -q torch==2.6.0 torchaudio==2.6.0 torchvision==0.21.0 "
       f"--index-url https://download.pytorch.org/whl/cu124", check=False)
    sh(f"{sys.executable} -m pip install -q 'numpy<2.1'", check=False)

    import torch, torchaudio
    from chatterbox.tts import ChatterboxTTS
    from safetensors.torch import load_file
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    os.makedirs(f"{WORK}/out", exist_ok=True)

    for h in HOSTS:
        ftp = f"/tmp/{h}.safetensors"
        sh(f"rclone copy {DRIVE}/s4/finetune_verbatim/{h}/t3_cfg.safetensors /tmp/{h}_ck/ -q", check=False)
        src = f"/tmp/{h}_ck/t3_cfg.safetensors"
        if not os.path.exists(src):
            print(f"[synth] no checkpoint for {h}, skip", flush=True); continue
        # a reference clip = the host's own first training clip
        os.makedirs(f"/tmp/{h}_ref", exist_ok=True)
        first = subprocess.run(f"rclone lsf {DRIVE}/hosts/{h}/clips | grep '.flac' | sort | head -1",
                               shell=True, capture_output=True, text=True).stdout.strip()
        sh(f"rclone copy '{DRIVE}/hosts/{h}/clips/{first}' /tmp/{h}_ref/ -q", check=False)
        ref = f"/tmp/{h}_ref/{first}"

        model = ChatterboxTTS.from_pretrained(device=dev)   # fresh per host
        model.t3.load_state_dict(load_file(src))
        print(f"[synth] {h}: loaded (ref={first})", flush=True)
        for i, text in enumerate(LINES):
            wav = model.generate(text, audio_prompt_path=ref,
                                 cfg_weight=GEN["cfg_weight"], exaggeration=GEN["exaggeration"])
            out = f"{WORK}/out/{h}_intro{i}.wav"
            torchaudio.save(out, wav.cpu() if hasattr(wav, "cpu") else wav, model.sr)
            sh(f"rclone copy {out} {DRIVE}/s4/out/ -q", check=False)
            print(f"[synth] {os.path.basename(out)}", flush=True)
        del model
        if dev == "cuda":
            torch.cuda.empty_cache()
    print("[synth] done", flush=True)


if __name__ == "__main__":
    main()
